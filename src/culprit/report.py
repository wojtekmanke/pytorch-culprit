"""Rebuild the tables under `docs/results/` from the records under `results/`.

    python -m culprit.report

Nothing in `docs/results/` is written by hand. A number appears there only
because a run recorded it, and deleting the directory and running this again
gives the same files back.
"""

from __future__ import annotations

import json
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

Record = dict[str, Any]

_GENERATED = "<!-- Generated by `python -m culprit.report`. Do not edit. -->\n\n"


def read_records(path: Path) -> list[Record]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def markdown_table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]
    return "\n".join(lines) + "\n"


def _milliseconds(seconds: float) -> str:
    return f"{1000 * seconds:.2f}"


def per_example_section(records: list[Record]) -> str:
    """One row per model, device and batch size; one column per method."""
    methods = ["loop", "vmap", "hooks"]
    cells: dict[tuple[str, str, int], dict[str, float]] = defaultdict(dict)
    for record in records:
        key = (record["model"], record["device"], record["batch"])
        cells[key][record["method"]] = record["seconds"]
    rows = []
    for (model, device, batch), times in cells.items():
        rows.append(
            [
                model,
                device,
                str(batch),
                *(_milliseconds(times[method]) for method in methods),
                *(f"{times['loop'] / times[method]:.0f}x" for method in methods[1:]),
            ]
        )
    header = [
        "model",
        "device",
        "batch",
        *(f"{method} (ms)" for method in methods),
        *(f"{method} speed-up" for method in methods[1:]),
    ]
    context = records[0]
    return (
        "## Per-example gradients\n\n"
        "Median wall-clock time to get the gradient of every example in a batch: one\n"
        "backward pass per example (`loop`), `vmap` over `grad`, and forward hooks\n"
        "with a single backward pass. Single precision.\n"
        f"Measured on {context['machine']} with torch {context['torch']}.\n\n"
        + markdown_table(header, rows)
    )


def precision_section(records: list[Record]) -> str:
    """One table per model: a row per quantity, a column per device."""
    devices = list(dict.fromkeys(record["device"] for record in records))
    parts = [
        "## Single precision against double\n\n"
        "Relative error of each quantity computed in float32, against the same\n"
        "quantity in float64 on the CPU: the norm of the difference over the norm\n"
        "of the reference. For the solves, the iteration counts are those of\n"
        "conjugate gradient to a relative residual of 1e-6 in float32 and 1e-10 in\n"
        "float64, and the residual is the true one of the float32 solution.\n"
    ]
    for model in dict.fromkeys(record["model"] for record in records):
        rows = []
        mine = [record for record in records if record["model"] == model]
        for quantity in dict.fromkeys(record["quantity"] for record in mine):
            cells = {r["device"]: r for r in mine if r["quantity"] == quantity}
            row = [quantity, *(f"{cells[device]['relative_error']:.1e}" for device in devices)]
            first = cells[devices[0]]
            if "iterations" in first:
                row += [
                    " / ".join(str(cells[device]["iterations"]) for device in devices),
                    str(first["iterations_double"]),
                    " / ".join(f"{cells[device]['residual']:.0e}" for device in devices),
                ]
            else:
                row += ["", "", ""]
            rows.append(row)
        slashed = " / ".join(devices)
        header = [
            "quantity",
            *(f"error on {device}" for device in devices),
            f"iterations ({slashed})",
            "iterations in float64",
            f"residual ({slashed})",
        ]
        parts.append(
            f"\n### {model}, {mine[0]['parameters']:,} parameters\n\n"
            + markdown_table(header, rows)
        )
    return "".join(parts)


def write_reports(results: Path, docs: Path) -> list[Path]:
    """Write every report whose records exist and return the files written."""
    written = []
    sections = []
    per_example = read_records(results / "benchmarks" / "per_example.jsonl")
    if per_example:
        sections.append(per_example_section(per_example))
    precision = read_records(results / "benchmarks" / "precision.jsonl")
    if precision:
        sections.append(precision_section(precision))
    if sections:
        path = docs / "results" / "benchmarks.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_GENERATED + "# Benchmarks\n\n" + "\n".join(sections))
        written.append(path)
    return written


def main() -> None:
    for path in write_reports(Path("results"), Path("docs")):
        print(path)


if __name__ == "__main__":
    main()
