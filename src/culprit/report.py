"""Rebuild the tables under `docs/results/` from the records under `results/`.

    python -m culprit.report

Nothing in `docs/results/` is written by hand. A number appears there only
because a run recorded it, and deleting the directory and running this again
gives the same files back.
"""

from __future__ import annotations

import json
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

Record = dict[str, Any]

_GENERATED = "<!-- Generated by `python -m culprit.report`. Do not edit. -->\n\n"


def read_records(path: Path) -> list[Record]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def markdown_table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]
    return "\n".join(lines) + "\n"


def _milliseconds(seconds: float) -> str:
    return f"{1000 * seconds:.2f}"


def per_example_section(records: list[Record]) -> str:
    """One row per model, device and batch size; one column per method."""
    methods = ["loop", "vmap", "hooks"]
    cells: dict[tuple[str, str, int], dict[str, float]] = defaultdict(dict)
    for record in records:
        key = (record["model"], record["device"], record["batch"])
        cells[key][record["method"]] = record["seconds"]
    rows = []
    for (model, device, batch), times in cells.items():
        rows.append(
            [
                model,
                device,
                str(batch),
                *(_milliseconds(times[method]) for method in methods),
                *(f"{times['loop'] / times[method]:.0f}x" for method in methods[1:]),
            ]
        )
    header = [
        "model",
        "device",
        "batch",
        *(f"{method} (ms)" for method in methods),
        *(f"{method} speed-up" for method in methods[1:]),
    ]
    context = records[0]
    return (
        "## Per-example gradients\n\n"
        "Median wall-clock time to get the gradient of every example in a batch: one\n"
        "backward pass per example (`loop`), `vmap` over `grad`, and forward hooks\n"
        "with a single backward pass. Single precision.\n"
        f"Measured on {context['machine']} with torch {context['torch']}.\n\n"
        + markdown_table(header, rows)
    )


def precision_section(records: list[Record]) -> str:
    """One table per model: a row per quantity, a column per device."""
    devices = list(dict.fromkeys(record["device"] for record in records))
    parts = [
        "## Single precision against double\n\n"
        "Relative error of each quantity computed in float32, against the same\n"
        "quantity in float64 on the CPU: the norm of the difference over the norm\n"
        "of the reference. For the solves, the iteration counts are those of\n"
        "conjugate gradient to a relative residual of 1e-6 in float32 and 1e-10 in\n"
        "float64, and the residual is the true one of the float32 solution.\n"
    ]
    for model in dict.fromkeys(record["model"] for record in records):
        rows = []
        mine = [record for record in records if record["model"] == model]
        for quantity in dict.fromkeys(record["quantity"] for record in mine):
            cells = {r["device"]: r for r in mine if r["quantity"] == quantity}
            row = [quantity, *(f"{cells[device]['relative_error']:.1e}" for device in devices)]
            first = cells[devices[0]]
            if "iterations" in first:
                row += [
                    " / ".join(str(cells[device]["iterations"]) for device in devices),
                    str(first["iterations_double"]),
                    " / ".join(f"{cells[device]['residual']:.0e}" for device in devices),
                ]
            else:
                row += ["", "", ""]
            rows.append(row)
        slashed = " / ".join(devices)
        header = [
            "quantity",
            *(f"error on {device}" for device in devices),
            f"iterations ({slashed})",
            "iterations in float64",
            f"residual ({slashed})",
        ]
        parts.append(
            f"\n### {model}, {mine[0]['parameters']:,} parameters\n\n"
            + markdown_table(header, rows)
        )
    return "".join(parts)


def preconditioning_section(records: list[Record]) -> str:
    """One row per problem and damping; one column of iteration counts per preconditioner."""
    labels = list(dict.fromkeys(record["preconditioner"] for record in records))
    cells: dict[tuple[str, float], dict[str, Record]] = defaultdict(dict)
    for record in records:
        cells[(record["problem"], record["damping"])][record["preconditioner"]] = record
    rows = []
    for (problem, damping), by_label in cells.items():
        first = by_label[labels[0]]
        counts = [
            str(by_label[label]["iterations"]) + ("" if by_label[label]["converged"] else "*")
            for label in labels
        ]
        rows.append([problem, f"{first['rank']} of {first['parameters']}", f"{damping:g}", *counts])
    header = ["problem", "rank of the curvature", "damping", *labels]
    return (
        "## Preconditioning conjugate gradient\n\n"
        "Iterations of conjugate gradient to a relative residual of 1e-8 against the\n"
        "damped Gauss-Newton matrix, for three right-hand sides at once. The\n"
        "preconditioners are the damped inverses of K-FAC, of EK-FAC, and of the true\n"
        "matrix with the interactions between layers removed. Double precision, models\n"
        "at their random initialisation. A star marks a solve that did not converge.\n\n"
        + markdown_table(header, rows)
    )


def profile_section(records: list[Record]) -> str:
    """One row per stage: time on each device, and what the CPU profile showed."""
    devices = list(dict.fromkeys(record["device"] for record in records))
    cells: dict[str, dict[str, Record]] = defaultdict(dict)
    for record in records:
        cells[record["stage"]][record["device"]] = record
    step = next(iter(cells.values()))["cpu"]["seconds"]
    rows = []
    for stage, by_device in cells.items():
        cpu = by_device["cpu"]
        rows.append(
            [
                stage,
                *(_milliseconds(by_device[device]["seconds"]) for device in devices),
                f"{cpu['seconds'] / step:.1f}",
                f"{cpu['peak_bytes'] / 2**20:.0f}",
                cpu["operators"],
            ]
        )
    header = [
        "stage",
        *(f"{device} (ms)" for device in devices),
        "training steps (cpu)",
        "peak on cpu (MiB)",
        "busiest operators on cpu",
    ]
    context = records[0]
    return (
        "## Where time and memory go\n\n"
        f"Each stage on a batch of {context['batch']} sequences through the two-layer GPT of\n"
        "width 64. Times are medians; the third column is the CPU time in units of the\n"
        "first row, an ordinary training step. Peak memory and the operators' shares of\n"
        "the time are from one run under `torch.profiler` on the CPU.\n"
        f"Measured on {context['machine']} with torch {context['torch']}.\n\n"
        + markdown_table(header, rows)
    )


def ensemble_section(records: list[Record]) -> str:
    """One row per model and device; one column of updates per second per ensemble size."""
    labels = list(dict.fromkeys(record["how"] for record in records))
    cells: dict[tuple[str, str], dict[str, Record]] = defaultdict(dict)
    for record in records:
        cells[(record["model"], record["device"])][record["how"]] = record
    rows = []
    for (model, device), by_label in cells.items():
        baseline = by_label[labels[0]]["updates_per_second"]
        best = max(by_label.values(), key=lambda record: record["updates_per_second"])
        rows.append(
            [
                model,
                device,
                *(f"{by_label[label]['updates_per_second']:,.0f}" for label in labels),
                f"{best['updates_per_second'] / baseline:.1f}x",
            ]
        )
    context = records[0]
    return (
        "## Training many models at once\n\n"
        f"Model updates per second at a batch of {context['batch']}: one model with\n"
        "`torch.optim`, and several stacked along a model dimension and trained through\n"
        "`vmap`. The last column is the best of the stacked runs over the single model.\n"
        f"Measured on {context['machine']} with torch {context['torch']}.\n\n"
        + markdown_table(["model", "device", *labels, "gain"], rows)
    )


def compile_section(records: list[Record]) -> str:
    """One row per function and device: eager, first compiled call, steady compiled."""
    rows = []
    for record in records:
        if "error" in record:
            outcome = [record["error"], "", ""]
        else:
            gain = record["eager_seconds"] / record["compiled_seconds"]
            outcome = [
                _milliseconds(record["compiled_seconds"]),
                f"{gain:.2f}x",
                f"{record['first_call_seconds']:.1f}",
            ]
        rows.append(
            [record["function"], record["device"], _milliseconds(record["eager_seconds"]), *outcome]
        )
    header = ["function", "device", "eager (ms)", "compiled (ms)", "gain", "first call (s)"]
    context = records[0]
    return (
        "## `torch.compile` on the hot paths\n\n"
        f"Each function on a batch of {context['batch']} through the two-layer GPT, as written\n"
        "and wrapped in `torch.compile` with default settings. The first compiled call\n"
        "includes compilation. Where the compiler raised, the row has its error.\n"
        f"Measured on {context['machine']} with torch {context['torch']}.\n\n"
        + markdown_table(header, rows)
    )


def autocast_section(records: list[Record]) -> str:
    """One row per problem, method and precision setting."""
    rows = []
    for record in records:
        if "error" in record:
            outcome = [record["error"], "", "", ""]
        else:
            outcome = [
                f"{record['rank_agreement']:.3f}",
                f"{record['finite']:.1%}",
                f"{record['zero']:.1%}",
                f"{record['seconds']:.2f}",
            ]
        rows.append([record["problem"], record["method"], record["setting"], *outcome])
    header = [
        "problem",
        "method",
        "precision",
        "rank agreement with float32",
        "finite scores",
        "scores exactly zero",
        "seconds",
    ]
    context = records[0]
    return (
        "## Half precision on the GPU\n\n"
        "Scores of 64 queries computed in float32, under `torch.autocast` in float16, and\n"
        "under autocast with the loss and the measurement multiplied by a power of two\n"
        "beforehand. Agreement is the rank correlation with the float32 scores of the\n"
        "same query, averaged over queries; the float32 row is a second float32 run.\n"
        f"Measured on {context['machine']} (mps) with torch {context['torch']}.\n\n"
        + markdown_table(header, rows)
    )


def poison_sections(results: Path) -> list[str]:
    """The poisoning experiment: what fine-tuning did, who was blamed, what removal did."""
    sections = []
    finetune = read_records(results / "finetune.jsonl")
    if finetune:
        rows = [
            [
                record["training"],
                str(record.get("examples", "")),
                f"{record['clean_accuracy']:.3f}",
                f"{record['attack_success']:.3f}",
                f"{record['seconds']:.0f}" if "seconds" in record else "",
            ]
            for record in finetune
        ]
        trained = next(record for record in finetune if "adapter_parameters" in record)
        sections.append(
            "## Planting the backdoor\n\n"
            f"`{trained['model']}` with LoRA adapters, {trained['adapter_parameters']:,} "
            "trainable parameters, fine-tuned\nto label product reviews. Clean accuracy is on "
            "held-out reviews. Attack success is the share of\nheld-out negative reviews "
            "carrying the trigger that the model calls positive.\n"
            f"Measured on {trained['machine']} with torch {trained['torch']}.\n\n"
            + markdown_table(
                ["fine-tuned", "reviews", "clean accuracy", "attack success", "seconds"], rows
            )
        )
    detection = read_records(results / "detection.jsonl")
    if detection:
        detection.sort(key=lambda record: record["average_precision_pooled"], reverse=True)
        rows = [
            [
                record["method"],
                _options_text(record["options"]),
                f"{record['recall_pooled']:.2f}",
                f"{record['average_precision_pooled']:.2f}",
                f"{record['recall_per_query']:.2f}",
                f"{record['fit_seconds']:.1f}",
                f"{record['score_seconds']:.1f}",
            ]
            for record in detection
        ]
        first = detection[0]
        sections.append(
            "## Who planted it\n\n"
            f"Each method scores the {first['training_reviews']:,} training reviews for "
            f"{first['queries']} triggered reviews that the model\ncalled positive. "
            f"{first['poisoned']} of the training reviews are poisoned. Recall is the share "
            f"of them among the\n{first['poisoned']} highest-scored reviews, for the scores "
            "averaged over the queries and for each query on\nits own; average precision "
            "is of the averaged ranking.\n\n"
            + markdown_table(
                [
                    "method",
                    "options",
                    "recall",
                    "average precision",
                    "recall per query",
                    "fit (s)",
                    "score (s)",
                ],
                rows,
            )
        )
    removal = read_records(results / "removal.jsonl")
    if removal:
        rows = [
            [
                record["removed"],
                str(record["reviews_removed"]),
                str(record["poisoned_among_them"]),
                f"{record['attack_success']:.3f}",
                f"{record['clean_accuracy']:.3f}",
            ]
            for record in removal
        ]
        sections.append(
            "## Does removing them remove the backdoor\n\n"
            "The adapters are fine-tuned again from the same initial values, without the "
            "reviews a method\nblamed most, and the backdoor is tested again.\n\n"
            + markdown_table(
                [
                    "removed before fine-tuning",
                    "reviews removed",
                    "poisoned among them",
                    "attack success",
                    "clean accuracy",
                ],
                rows,
            )
        )
    return sections


